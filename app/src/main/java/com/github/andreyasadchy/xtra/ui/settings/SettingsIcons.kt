    /** Icon for an individual setting, matched on its key. Falls back to a generic tune icon. */
    @DrawableRes
    fun forSetting(key: String?): Int {
        key?.let { keyIcons[it] }?.let { return it }
        val lower = key?.lowercase() ?: return R.drawable.ic_pref_tune
        return rules.firstOrNull { it.first.containsMatchIn(lower) }?.second ?: R.drawable.ic_pref_tune
    }
