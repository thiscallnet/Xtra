    /** Icon for a section header, matched on the section's title text. Null when unmapped. */
    @DrawableRes
    fun forCategory(title: CharSequence?, resolve: (Int) -> String): Int? {
        if (title.isNullOrEmpty()) return null
        val text = title.toString()
        return categoryIcons.firstOrNull { resolve(it.first) == text }?.second
    }

    /** Navigation rows (sub-pages) get a badge. */
    @DrawableRes
    fun forPage(key: String?): Int? = key?.let { pageIcons[it] }

